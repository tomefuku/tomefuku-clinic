def specialty_tags():
    return "".join(f'<a href="@@/specialty/{s}/">{n}</a>' for s, n, _ in SPECIALTY_LIST)


def area_tags():
    return "".join(f'<a href="@@/area/{a["slug"]}/">{a["name"]}</a>' for a in AREAS)


def related(exclude):
    items = [(f"@@/{p}", n, d) for p, n, d in SERVICES if p != exclude]
    return section("RELATED", "関連するサービス。", link_cards(items), band=True)


def specialty_area_block(title_prefix):
    return section("CLINIC / AREA", f"{title_prefix}の診療科目・対応エリア。", f'''      <div class="fb-wrap">
        <div class="fb-col"><h3>診療科目別のご案内</h3><div class="tag-list">{specialty_tags()}</div></div>
        <div class="fb-col"><h3>対応エリア</h3><div class="tag-list">{area_tags()}</div></div>
      </div>''')


def price_rows_area(key):
    return [(label, price_or_estimate(v)) for label, v in PRICES[key]]


